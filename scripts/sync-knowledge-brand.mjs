import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

// Package the canonical web stylesheet and mark for deployments outside the design repository.
const brand = join(process.env.ACORU_DESIGN_SYSTEM_DIR ?? "C:/dev/.acoru-design-system", "brand");
const output = new URL("../public/brand/", import.meta.url);
await mkdir(output, { recursive: true });
const css = await readFile(join(brand, "brand.css"), "utf8");
if (!css.includes(":root {")) throw new Error("Expected the canonical brand.css root selector.");
await writeFile(new URL("../src/app/knowledge/brand.generated.css", import.meta.url),
  "/* Generated by scripts/sync-knowledge-brand.mjs from brand/brand.css. */\n" +
  css.replace(":root {", ".knowledge-shell {"));
await copyFile(join(brand, "logos", "acoru-mark-primary.png"), new URL("acoru-mark-primary.png", output));
